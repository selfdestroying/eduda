-- Строка про `/stop` переезжает из рендера в шаблон.
--
-- Раньше её дописывал `renderReminderTemplate` и стереть её было нельзя. Теперь
-- это обычный текст шаблона: школа вправе переписать его целиком, а сама
-- команда `/stop` работает независимо от того, упомянута ли она в сообщении.
--
-- Дописывается только тем, у кого шаблон не тронут: у остальных там уже их
-- собственный текст, и лезть в него нельзя. Сообщение при этом не меняется ни
-- на символ — рендер добавлял ровно эту строку ровно в это место.

ALTER TABLE "Organization" ALTER COLUMN "reminderTemplate" SET DEFAULT '{когда}

{занятия}

Не сможете прийти — отметьте в кабинете.

Отключить напоминания — /stop';

UPDATE "Organization"
SET "reminderTemplate" = "reminderTemplate" || E'\n\nОтключить напоминания — /stop'
WHERE "reminderTemplate" = '{когда}

{занятия}

Не сможете прийти — отметьте в кабинете.';
