-- Шаблон сообщения, который школа правит сама.
--
-- Дефолт повторяет текст, который бот собирал до этого, поэтому у школ, которые
-- шаблон не тронут, сообщение не изменится ни на символ. Подстановки живут в
-- `@repo/core/reminder-template`, там же проверка и рендер.
--
-- Строки отписки в шаблоне нет намеренно: `/stop` дописывает рендер, и стереть
-- её школа не может — иначе у родителя не остаётся способа отписаться в чате.

ALTER TABLE "Organization"
    ADD COLUMN "reminderTemplate" TEXT NOT NULL
    DEFAULT '{когда}

{занятия}

Не сможете прийти — отметьте в кабинете.';
