-- Строка занятия становится вторым шаблоном.
--
-- До этого её формат был зашит в планировщике, и школа не могла ни убрать место,
-- ни переставить курс с именем. Отдельным шаблоном она потому, что рендерится на
-- КАЖДОЕ занятие: у родителя двое детей — это две строки в одном сообщении, и
-- `{ученик}` с `{курс}` принадлежат строке, а не письму.
--
-- Дефолт повторяет прежний зашитый формат, поэтому сообщение не меняется.

ALTER TABLE "Organization"
    ADD COLUMN "reminderLineTemplate" TEXT NOT NULL
    DEFAULT '• {ученик} — {курс}, {время}, {место}';
