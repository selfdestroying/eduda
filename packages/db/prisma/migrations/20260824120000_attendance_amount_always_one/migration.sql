-- Количество уроков в строке посещения теперь всегда 1, а «оплачено ли занятие»
-- переезжает на `price`: NULL — цены ещё нет, число — цена застыла при списании.
--
-- Раньше признаком было `amount = 0`, и им же помечались занятия, которых с
-- денежной точки зрения не было вовсе (не отмечено, предупреждённый пропуск).
-- Из-за этого «урок не оплачен» и «урок не считается» были в базе неотличимы.

-- 1. Строки без списания теряют цену: у них стоял ноль от бэкфилла, а ноль —
--    это утверждение «урок стоил 0 ₽», которого никто не делал.
UPDATE "Attendance" SET "price" = NULL WHERE "amount" = 0 OR "amount" IS NULL;

-- 2. Количество выравнивается. Занятия, списанные «в долг» до перехода
--    10.08.2026, уже имеют amount = 1 с выданной тогда ценой — их не трогаем,
--    иначе поедет выручка закрытых месяцев.
UPDATE "Attendance" SET "amount" = 1 WHERE "amount" IS NULL OR "amount" = 0;

-- 3. Ноль и NULL в этой колонке больше не значат ничего — запрещаем их.
ALTER TABLE "Attendance" ALTER COLUMN "amount" SET DEFAULT 1,
                         ALTER COLUMN "amount" SET NOT NULL;
