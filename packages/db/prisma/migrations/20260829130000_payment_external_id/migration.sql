-- Внешний ключ счёта: его id в amoCRM.
--
-- Опрос CRM идёт скользящим окном в неделю, а не курсором «с чего продолжили»,
-- поэтому один и тот же оплаченный счёт попадает в выборку около тысячи раз.
-- Без этой колонки столько же оплат и заведётся.
--
-- Курсор вместо ключа не помогает: падение между записью оплаты и записью
-- курсора даёт дубль, а простой парсера — потерю. Узнавать счёт по совпадению
-- суммы, даты и ученика тоже нельзя: родитель платит за двоих детей одинаковыми
-- абонементами в один день, и второй платёж не завёлся бы.
--
-- Уникальность в пределах школы: аккаунт CRM у каждой свой, и номера счетов в
-- разных аккаунтах совпадают свободно. NULL уникальность не задевает, так что
-- оплат, заведённых руками, ограничение не касается.
ALTER TABLE "Payment" ADD COLUMN "externalId" INTEGER;

CREATE UNIQUE INDEX "Payment_organizationId_externalId_key" ON "Payment"("organizationId", "externalId");
