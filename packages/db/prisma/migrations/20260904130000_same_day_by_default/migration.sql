-- «В день занятия за два часа» — режим по умолчанию.
--
-- Напоминание накануне вечером к моменту занятия успевает забыться, а за два
-- часа приходит тогда, когда ещё можно собраться. Часовой запас уже стоит
-- дефолтом у `reminderLeadMinutes`.
--
-- Заодно переводятся школы, которые рассылку ни разу не включали: значение у
-- них досталось от прежнего дефолта колонки, а не от чьего-то выбора, и без
-- этого новый дефолт не увидел бы никто. У школ с включённой рассылкой режим
-- остаётся тот, что они выбрали.

ALTER TABLE "Organization" ALTER COLUMN "reminderMode" SET DEFAULT 'SAME_DAY';

UPDATE "Organization" SET "reminderMode" = 'SAME_DAY' WHERE "remindersEnabled" = false;
