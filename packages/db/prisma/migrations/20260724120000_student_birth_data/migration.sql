-- Приведение в порядок данных о рождении ученика: чистка `birthDate` и удаление
-- производной колонки `age`.
--
-- ─── Почему чистятся даты ───────────────────────────────────────────────────
--
-- Из 632 заполненных `birthDate` настоящей датой рождения человека выглядели
-- около 120. Остальное — следы импортов, три образца:
--
--   1. Мусор без информации: `1900-01-01`, `2000-01-01` — возраст за двадцать,
--      таких учеников в этих школах не бывает.
--   2. `YYYY-01-01` — «известен только год рождения», день и месяц подставлены.
--      420 штук, размазанных по годам 2010–2021.
--   3. Одна и та же дата у десятков учеников одной школы (`2013-02-20` × 90).
--
-- Правило намеренно НЕ перечисляет конкретные школы и даты: в проде id и
-- значения другие. Порог в 10 учеников с точностью до дня — это уже не
-- совпадение, а импорт: в школе на несколько сотен человек столько настоящих
-- совпадений не бывает. Граница «старше 20» зафиксирована датой, а не
-- выражением от now(), чтобы миграция отработала одинаково в любой момент.
--
-- Что теряем: у дат вида `YYYY-01-01` настоящим был год, то есть примерный
-- возраст. Он всё равно врал в пределах года, а цена его хранения — подарок ко
-- дню рождения четырём сотням учеников первого января. Настоящую дату школа
-- собирает формой актуализации данных.
--
-- `birthDate` — date-only строка `YYYY-MM-DD`, сравнивается лексикографически
-- = хронологически, поэтому обычного `<` достаточно.
WITH bulk AS (
    SELECT "organizationId", "birthDate"
    FROM "Student"
    WHERE "birthDate" IS NOT NULL
    GROUP BY 1, 2
    HAVING count(*) >= 10
)
UPDATE "Student" s
SET "birthDate" = NULL
WHERE s."birthDate" IS NOT NULL
  AND (
    s."birthDate" < '2006-07-24'
    OR substring(s."birthDate" FROM 6) = '01-01'
    OR EXISTS (
        SELECT 1 FROM bulk b
        WHERE b."organizationId" = s."organizationId"
          AND b."birthDate" = s."birthDate"
    )
  );

-- ─── Почему удаляется age ───────────────────────────────────────────────────
--
-- Возраст полностью выводится из `birthDate` (`getAgeFromBirthDate`) и теперь
-- считается на чтение. Колонка была кешем, который обновлялся только при
-- сохранении карточки ученика, поэтому после дня рождения показывала
-- прошлогоднее число.
--
-- Данные не теряются: где `birthDate` заполнена, возраст восстанавливается
-- вычислением. Где не заполнена — возраст всё равно был неправдой.
ALTER TABLE "Student" DROP COLUMN "age";
