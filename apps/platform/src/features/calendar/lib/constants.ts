/**
 * Палитра цветов для категорий календаря — ступень 600 палитры Tailwind.
 * Цвет детерминирован по id, чтобы быть стабильным между запросами.
 *
 * Ссылками, а не литералами: раньше здесь стояли hex времён Tailwind v3, и
 * после перехода на v4 ни одно из десяти значений уже не совпадало с палитрой
 * (`#2563eb` против нынешнего `#155dfc` и так все десять). Ссылка от версии не
 * отстаёт. Держать их литералами заставлял `hexA`, который умел только hex; он
 * переписан на `color-mix` и теперь принимает любой цвет.
 *
 * Это цвета **данных**, а не статусов: они одинаковы в обеих темах намеренно —
 * цвет курса не должен меняться от переключения темы.
 */
export const COURSE_PALETTE = [
  'var(--color-blue-600)',
  'var(--color-orange-600)',
  'var(--color-green-600)',
  'var(--color-purple-600)',
  'var(--color-amber-600)',
  'var(--color-cyan-600)',
  'var(--color-pink-600)',
  'var(--color-lime-600)',
  'var(--color-red-600)',
  'var(--color-indigo-600)',
]

/** Стабильный цвет по числовому id (детерминирован, для свотчей фильтров). */
export const colorForId = (id: number) => COURSE_PALETTE[Math.abs(id) % COURSE_PALETTE.length]!

/** Стабильный цвет типа группы по его id (цвет события на календаре). */
export const colorForGroupType = colorForId

/**
 * Цвет линии «сейчас» и акцента «сегодня» на мобильных.
 *
 * Здесь стоял литерал `oklch(0.541 0.281 293.009)` — фиолетовый, бывший когда-то
 * основным цветом. Комментарий уверял, что это primary, но связи не было, и
 * после смены темы календарь остался фиолетовым в одиночку.
 */
export const NOW_COLOR = 'var(--primary)'

